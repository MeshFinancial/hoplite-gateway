# Session discovery
# ---------------------------------------------------------------------------

async def _find_authorized_sessions(count: int) -> list[tuple[str, int, str, str]]:
    """Find *count* authorized sessions.  Returns [(path, api_id, api_hash, phone)]."""
    sessions = _collect_sessions()
    random.shuffle(sessions)
    result: list[tuple[str, int, str, str]] = []
    for sess_path in sessions:
        if len(result) >= count:
            break
        api_id, api_hash = _load_session_meta(sess_path)
        phone = os.path.basename(sess_path).replace(".session", "")
        try:
            from telethon import TelegramClient
            client = TelegramClient(sess_path, api_id, api_hash)
            await client.connect()
            if await client.is_user_authorized():
                result.append((sess_path, api_id, api_hash, phone))
                logger.debug("found authorized session: %s", phone)
            await client.disconnect()
        except Exception:
            pass
    return result


