"""Proxy auto-provisioning engine — generates hardsession proxies from @bpproxy_bot.

Integrates with the BulletProof Proxy Telegram bot via Telethon using pre-authorized
TG sessions.  On demand it walks the bot menu (/start → Русский → согласен → бонус →
меню → Ротационные → Residential/Datacenter → Сессия → Получить прокси), extracts
the proxy URL from the bot reply, and stores it in the proxy pool (SQLite).

The engine is fully async and designed to be called from the FastAPI task runtime
or directly from any async context:

    provisioner = ProxyProvisioner()
    result = await provisioner.provision(count=5, proxy_type="residential")

Source: ported from C:/Users/User/tmp/mass_bpproxy.py and bpproxy_bot.py.
"""
