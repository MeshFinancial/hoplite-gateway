@dataclass
class ProvisionedProxy:
    """A single proxy generated by the bot."""
    url: str
    proxy_type: str          # "residential" | "datacenter"
    phone: str               # TG session phone that generated it
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))

    def to_dict(self) -> dict:
        return {
            "url": self.url,
            "type": self.proxy_type,
            "phone": self.phone,
            "created_at": self.created_at.isoformat(),
        }


@dataclass
class ProvisionResult:
    """Aggregate result of a provisioning run."""
    requested: int
    generated: list[ProvisionedProxy] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)

    @property
    def success_count(self) -> int:
        return len(self.generated)

    def to_dict(self) -> dict:
        return {
            "requested": self.requested,
            "generated": [p.to_dict() for p in self.generated],
            "errors": self.errors,
            "success_count": self.success_count,
        }


