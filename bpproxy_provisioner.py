# DB integration
# ---------------------------------------------------------------------------

def _store_proxies(proxies: list[ProvisionedProxy]) -> int:
    """Store provisioned proxies in the SQLite proxy pool.

    Uses a lazy import so the provisioner can run standalone without the DB
    module being present.  Returns the number of proxies actually stored
    (duplicates are skipped).
    """
    if not proxies:
        return 0

    try:
        from sqlmodel import Session as DBSession, select
        from core.db import ProxyModel, engine
    except Exception:
        # DB not available — write to fallback file so proxies are not lost
        _fallback_store(proxies)
        return len(proxies)

    stored = 0
    with DBSession(engine) as s:
        for p in proxies:
            existing = s.exec(
                select(ProxyModel).where(ProxyModel.url == p.url)
            ).first()
            if existing:
                # Already in pool — re-activate if it was disabled
                if not existing.is_active:
                    existing.is_active = True
                    s.add(existing)
                continue
            model = ProxyModel(
                url=p.url,
                type=p.proxy_type,
                region="",
                is_active=True,
                last_checked=datetime.now(timezone.utc),
            )
            s.add(model)
            stored += 1
        s.commit()
    logger.info("stored %d new proxies in DB pool", stored)
    return stored


def _fallback_store(proxies: list[ProvisionedProxy]) -> None:
    """Append proxies to a text file when the DB is unavailable."""
    path = os.environ.get(
        "BPPROXY_FALLBACK_FILE",
        os.path.join(os.path.dirname(__file__), "..", "bpproxy_pool.txt"),
    )
    path = os.path.normpath(path)
    with open(path, "a", encoding="utf-8") as f:
        for p in proxies:
            f.write(f"# {p.phone} | {p.proxy_type} | {p.created_at.isoformat()}\n")
            f.write(f"{p.url}\n")
    logger.info("fallback-stored %d proxies to %s", len(proxies), path)


