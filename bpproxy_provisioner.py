async def _click_button(client, entity, button_text: str, wait: float = _CLICK_WAIT) -> bool:
    """Find the latest bot message with a button matching *button_text* and click it."""
    best_msg = None
    best_btn = None
    async for msg in client.iter_messages(entity, limit=20):
        if msg.sender_id != entity.id or not msg.buttons:
            continue
        for row in msg.buttons:
            for btn in row:
                btn_text = btn.text if hasattr(btn, "text") else str(btn)
                if button_text.lower() in btn_text.lower():
                    if best_msg is None or msg.id > best_msg.id:
                        best_msg = msg
                        best_btn = btn
                    break
    if not best_msg or not best_btn:
        return False
    try:
        await best_btn.click()
        await asyncio.sleep(wait)
        return True
    except Exception as exc:
        logger.debug("click_button %r failed: %s", button_text, exc)
        return False


async def _extract_proxy(client, entity, after_id: int) -> Optional[str]:
    """Look for a proxy string in bot messages newer than *after_id*."""
    async for msg in client.iter_messages(entity, min_id=after_id, limit=5):
        if msg.sender_id != entity.id:
            continue
        m = PROXY_RE.search(msg.text or "")
        if m:
            return m.group(1)
    return None


async def _get_latest_msg_id(client, entity) -> int:
    async for msg in client.iter_messages(entity, limit=1):
        return msg.id
    return 0


async def _navigate_to_rotational(client, entity) -> bool:
    """Run the onboarding flow: /start → Русский → согласен → бонус → меню → Ротационные.

    Returns True if we successfully reached the rotational proxy submenu.
    """
    # /start
    await client.send_message(entity, "/start")
    await asyncio.sleep(_START_WAIT)

    # Русский (language selection — only on first contact)
    await _click_button(client, entity, "Русский", wait=_NAV_WAIT)

    # согласен (terms acceptance)
    await _click_button(client, entity, "согласен", wait=_NAV_WAIT)

    # Получить бонус (free trial bonus)
    await _click_button(client, entity, "Получить бонус", wait=_NAV_WAIT)

    # Открыть меню
    ok = await _click_button(client, entity, "Открыть меню", wait=_NAV_WAIT)
    if not ok:
        # Maybe already in menu — retry /start
        await client.send_message(entity, "/start")
        await asyncio.sleep(_START_WAIT)
        await _click_button(client, entity, "Открыть меню", wait=_NAV_WAIT)

    # Ротационные
    ok = await _click_button(client, entity, "Ротационные", wait=_NAV_WAIT)
    if not ok:
        logger.warning("navigate_to_rotational: no 'Ротационные' button")
        return False
    return True


async def _acquire_one_type(
    client, entity, proxy_type: str
) -> Optional[str]:
    """From the rotational submenu, acquire a single hardsession proxy of *proxy_type*.

    *proxy_type* must be "Residential" or "Datacenter" (case-insensitive match on
    button text).  Assumes we are currently in the rotational submenu.
    """
    # Click the proxy type button
    ok = await _click_button(client, entity, proxy_type, wait=_NAV_WAIT)
    if not ok:
        logger.warning("acquire_one_type: no %r button", proxy_type)
        return None

    # Switch to hardsession mode (Сессия)
    await _click_button(client, entity, "Сессия", wait=_NAV_WAIT)

    # Record msg id before requesting, so we can find the new proxy message
    before_id = await _get_latest_msg_id(client, entity)

    # Получить прокси
    ok = await _click_button(client, entity, "Получить прокси", wait=_EXTRACT_WAIT)
    if not ok:
        logger.warning("acquire_one_type: no 'Получить прокси' button for %s", proxy_type)
        return None

    proxy = await _extract_proxy(client, entity, before_id)
    if not proxy:
        logger.warning("acquire_one_type: no proxy string found for %s", proxy_type)
    return proxy


async def _process_session(
    sess_path: str,
    api_id: int,
    api_hash: str,
    phone: str,
    want_residential: bool,
    want_datacenter: bool,
) -> list[ProvisionedProxy]:
    """Full flow for one TG session: onboarding + hardsession proxies.

    Returns a list of ProvisionedProxy objects (0–2 entries).
    """
    from telethon import TelegramClient

    client = TelegramClient(sess_path, api_id, api_hash)
    await client.connect()
    if not await client.is_user_authorized():
        logger.debug("session %s not authorized — skipping", phone)
        await client.disconnect()
        return []

    entity = await client.get_entity(BOT_USERNAME)
    results: list[ProvisionedProxy] = []

    try:
        if not await _navigate_to_rotational(client, entity):
            return []

        # --- Residential ---
        if want_residential:
            proxy = await _acquire_one_type(client, entity, "Residential")
            if proxy:
                results.append(ProvisionedProxy(
                    url=proxy, proxy_type="residential", phone=phone,
                ))
                logger.info("[%s] RES: %s", phone, proxy)

        # --- Datacenter ---
        if want_datacenter:
            # Go back to rotational submenu
            await _click_button(client, entity, "Назад", wait=_NAV_WAIT)
            # If Назад didn't work, re-navigate
            if not await _click_button(client, entity, "Datacenter", wait=_NAV_WAIT):
                await _click_button(client, entity, "Назад", wait=_NAV_WAIT)
                await _click_button(client, entity, "Ротационные", wait=_NAV_WAIT)

            proxy = await _acquire_one_type(client, entity, "Datacenter")
            if proxy:
                results.append(ProvisionedProxy(
                    url=proxy, proxy_type="datacenter", phone=phone,
                ))
                logger.info("[%s] DC:  %s", phone, proxy)

    except Exception as exc:
        logger.error("session %s error: %s", phone, exc)
    finally:
        await client.disconnect()

    return results


