# Matches proxy URLs emitted by the bot:  http://bpuser-XXX@host:port
PROXY_RE = re.compile(r"(https?://bpuser-[^\s`]+@[\w.-]+:\d+)")

# Bot menu navigation delays (seconds).  Kept short for speed but long enough
# for the bot to respond.
_NAV_WAIT = 4
_CLICK_WAIT = 4
_EXTRACT_WAIT = 5
_START_WAIT = 3


def _sessions_dirs() -> list[str]:
    env = os.environ.get("BPPROXY_SESSIONS_DIRS", "")
    if env:
        return [d.strip() for d in env.split(os.pathsep) if d.strip()]
    return _DEFAULT_SESSIONS_DIRS


def _load_session_meta(sess_path: str) -> tuple[int, str]:
    """Load api_id / api_hash from the sibling .json file, fall back to defaults."""
    json_path = sess_path.replace(".session", ".json")
    api_id = DEFAULT_API_ID
    api_hash = DEFAULT_API_HASH
    if os.path.exists(json_path):
        try:
            with open(json_path, "r", encoding="utf-8") as fh:
                meta = json.load(fh)
            api_id = int(meta.get("app_id") or meta.get("api_id") or DEFAULT_API_ID)
            api_hash = meta.get("app_hash") or meta.get("api_hash") or DEFAULT_API_HASH
        except Exception:
            pass
    return api_id, api_hash


def _collect_sessions() -> list[str]:
    """Glob all *.session files from configured directories."""
    sessions: list[str] = []
    for d in _sessions_dirs():
        sessions.extend(glob.glob(os.path.join(d, "*.session")))
    return sessions


