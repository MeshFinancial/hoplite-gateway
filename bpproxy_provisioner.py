class ProxyProvisioner:
    """Auto-provisioning engine for @bpproxy_bot hardsession proxies.

    Usage::

        prov = ProxyProvisioner()
        result = await prov.provision(count=5, proxy_type="residential")
        # result.generated → list[ProvisionedProxy]
    """

    async def provision(
        self,
        count: int = 5,
        proxy_type: str = "both",
        store: bool = True,
    ) -> ProvisionResult:
        """Generate *count* hardsession proxies via @bpproxy_bot.

        Args:
            count: Number of TG sessions to use (each yields up to 2 proxies).
            proxy_type: "residential", "datacenter", or "both".
            store: If True, store results in the DB proxy pool.

        Returns:
            ProvisionResult with generated proxies and any errors.
        """
        want_res = proxy_type in ("residential", "both", "all")
        want_dc = proxy_type in ("datacenter", "both", "all")

        result = ProvisionResult(requested=count)

        logger.info("provisioning %d sessions (type=%s)", count, proxy_type)
        sessions = await _find_authorized_sessions(count)
        if not sessions:
            result.errors.append("No authorized TG sessions found")
            return result

        logger.info("found %d authorized sessions", len(sessions))

        for sess_path, api_id, api_hash, phone in sessions:
            try:
                proxies = await _process_session(
                    sess_path, api_id, api_hash, phone,
                    want_residential=want_res,
                    want_datacenter=want_dc,
                )
                result.generated.extend(proxies)
            except Exception as exc:
                result.errors.append(f"{phone}: {exc}")
                logger.error("session %s failed: %s", phone, exc)

        if store and result.generated:
            _store_proxies(result.generated)

        logger.info(
            "provisioning complete: %d/%d proxies from %d sessions, %d errors",
            result.success_count, count * (2 if (want_res and want_dc) else 1),
            len(sessions), len(result.errors),
        )
        return result

    async def provision_residential(self, count: int = 5) -> ProvisionResult:
        """Shortcut: provision only residential hardsession proxies."""
        return await self.provision(count=count, proxy_type="residential")

    async def provision_datacenter(self, count: int = 5) -> ProvisionResult:
        """Shortcut: provision only datacenter hardsession proxies."""
        return await self.provision(count=count, proxy_type="datacenter")

    async def provision_both(self, count: int = 5) -> ProvisionResult:
        """Shortcut: provision both residential + datacenter from each session."""
        return await self.provision(count=count, proxy_type="both")

    async def check_sessions(self) -> dict:
        """Return a summary of available TG sessions.

        Useful for the dashboard / API to show how many sessions are ready.
        """
        all_sessions = _collect_sessions()
        authorized = await _find_authorized_sessions(len(all_sessions))
        return {
            "total_sessions": len(all_sessions),
            "authorized_sessions": len(authorized),
            "sessions_dirs": _sessions_dirs(),
        }


# Module-level singleton for convenience
provisioner = ProxyProvisioner()


# ---------------------------------------------------------------------------
# CLI entry point (mirrors mass_bpproxy.py usage)
# ---------------------------------------------------------------------------

async def _cli() -> None:
    import sys
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    ptype = sys.argv[2] if len(sys.argv) > 2 else "both"
    result = await provisioner.provision(count=count, proxy_type=ptype)
    print(json.dumps(result.to_dict(), indent=2, ensure_ascii=False))


if __name__ == "__main__":
    asyncio.run(_cli())
